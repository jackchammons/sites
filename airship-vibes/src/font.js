export const GLYPH_W = 5, GLYPH_H = 7;
export const hasGlyph = ch => Object.prototype.hasOwnProperty.call(G, ch);

/* One line of text as a bitmap: a byte per pixel, 255 where there is ink,
   rows top to bottom. A character the face lacks is drawn as a space. */
export function renderText(text) {
  const chars = [...String(text).toUpperCase()];
  const width = Math.max(1, chars.length * (GLYPH_W + 1) - 1), height = GLYPH_H;
  const data = new Uint8Array(width * height);
  chars.forEach((ch, i) => {
    const rows = (G[ch] || G[' ']).split('|');
    for (let y = 0; y < GLYPH_H; y++) {
      for (let x = 0; x < GLYPH_W; x++) {
        if (rows[y][x] === '#') data[y * width + i * (GLYPH_W + 1) + x] = 255;
      }
    }
  });
  return { width, height, data };
}
